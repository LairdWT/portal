// Compile-time freeze contract for the TYPE-ONLY public-API barrel exports (1.0
// stabilization, Track 3). Companion guard to index.barrel.test.ts, which
// snapshots the runtime VALUE exports, and index.contract.test.ts, which pins
// individual prop shapes. Because index.barrel.test.ts snapshots
// Object.keys(barrel) and type-only exports are erased at runtime, a deleted
// `export { type X }` line in src/index.ts is invisible to every runtime gate.
//
// This file closes that hole: the `import type { ... }` above names every
// type-only barrel export, so removing any one of them makes its specifier
// unresolvable and `pnpm typecheck` (tsc -b) fails. The tuple below references
// each imported name exactly once, so none is reported as an unused import; the
// five generic props are instantiated only to form a valid type reference.
// ADDING a new type export does not fail here - nothing references the new name
// - so the freeze stays additive-optional. EWindowFrame is a value+type export
// (S8, additive); it is pinned here as a type on top of the value snapshot.
